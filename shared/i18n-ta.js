/** Dates and times: weekday and month names, am / pm. Only for strings that are a date or time. */
function dateText(s) {
  if (!/\d/.test(s) || !/^[A-Za-z0-9,:.\s–-]+$/.test(s)) return null;
  if (!DATE_WORDS.test(s)) return null;
  DATE_WORDS.lastIndex = 0;
  if (/[A-Za-z]/.test(s.replace(DATE_WORDS, ''))) return null;
  return s
    .replace(/\b(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday)\b/g, (m) => DAY_FULL[m])
    .replace(/\b(January|February|March|April|June|July|August|September|October|November|December)\b/g, (m) => MONTH_FULL[m])
    .replace(/\b(Mon|Tue|Wed|Thu|Fri|Sat|Sun)\b/g, (m) => DAY[m])
    .replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b/g, (m) => MONTH[m])
    .replace(/\b(am|AM)\b/g, 'முப')
    .replace(/\b(pm|PM)\b/g, 'பிப');
}

